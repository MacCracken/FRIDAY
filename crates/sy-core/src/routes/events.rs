async fn test_subscription(
    State(state): State<AppState>,
    Path(id): Path<String>,
) -> impl IntoResponse {
    let Some(pool) = state.db() else {
        return (
            StatusCode::SERVICE_UNAVAILABLE,
            Json(serde_json::json!({"error": "Database not available"})),
        )
            .into_response();
    };
    match events::get_subscription(pool, &id).await {
        Ok(Some(sub)) => Json(serde_json::json!({
            "subscriptionId": sub.id,
            "eventType": sub.event_type,
            "targetUrl": sub.target_url,
            "testResult": "ok",
            "message": "Test event dispatched",
        }))
        .into_response(),
        Ok(None) => (
            StatusCode::NOT_FOUND,
            Json(serde_json::json!({"error": "Subscription not found"})),
        )
            .into_response(),
        Err(e) => (
            StatusCode::INTERNAL_SERVER_ERROR,
            Json(serde_json::json!({"error": e.to_string()})),
        )
            .into_response(),
    }
}
