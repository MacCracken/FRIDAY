//! Capture routes — consent management for data capture.

use axum::extract::{Path, Query, State};
use axum::http::StatusCode;
use axum::response::IntoResponse;
use axum::routing::{get, post};
use axum::{Json, Router};
use serde::Deserialize;

use crate::db::capture;
use crate::state::AppState;

pub fn router() -> Router<AppState> {
    Router::new()
        .route("/api/v1/capture/consent/request", post(request_consent))
        .route("/api/v1/capture/consent/pending", get(list_pending))
        .route("/api/v1/capture/consent/{id}", get(get_consent))
        .route("/api/v1/capture/consent/{id}/grant", post(grant_consent))
        .route("/api/v1/capture/consent/{id}/deny", post(deny_consent))
        .route("/api/v1/capture/consent/{id}/revoke", post(revoke_consent))
}

#[derive(Deserialize)]
struct PaginationQuery {
    #[serde(default = "default_limit")]
    limit: i64,
    #[serde(default)]
    offset: i64,
}

fn default_limit() -> i64 {
    20
}

#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
struct ConsentRequest {
    subject: String,
    purpose: String,
    data_types: Option<Vec<String>>,
    expires_at: Option<i64>,
}

/// POST /api/v1/capture/consent/request — create a new consent request.
async fn request_consent(
    State(state): State<AppState>,
    Json(body): Json<ConsentRequest>,
) -> impl IntoResponse {
    let Some(pool) = state.db() else {
        return (
            StatusCode::SERVICE_UNAVAILABLE,
            Json(serde_json::json!({"error": "Database not available"})),
        )
            .into_response();
    };
    let id = uuid::Uuid::now_v7().to_string();
    let data_types = serde_json::to_value(&body.data_types).unwrap_or_default();
    match capture::create_consent(
        pool,
        &id,
        &body.subject,
        &body.purpose,
        &data_types,
        body.expires_at,
    )
    .await
    {
        Ok(row) => (
            StatusCode::CREATED,
            Json(serde_json::to_value(row).unwrap()),
        )
            .into_response(),
        Err(e) => (
            StatusCode::INTERNAL_SERVER_ERROR,
            Json(serde_json::json!({"error": e.to_string()})),
        )
            .into_response(),
    }
}

/// GET /api/v1/capture/consent/pending — list pending consent requests.
async fn list_pending(
    State(state): State<AppState>,
    Query(q): Query<PaginationQuery>,
) -> impl IntoResponse {
    let Some(pool) = state.db() else {
        return (
            StatusCode::SERVICE_UNAVAILABLE,
            Json(serde_json::json!({"error": "Database not available"})),
        )
            .into_response();
    };
    match capture::list_pending(pool, q.limit.min(100), q.offset).await {
        Ok(rows) => Json(serde_json::to_value(rows).unwrap()).into_response(),
        Err(e) => (
            StatusCode::INTERNAL_SERVER_ERROR,
            Json(serde_json::json!({"error": e.to_string()})),
        )
            .into_response(),
    }
}

